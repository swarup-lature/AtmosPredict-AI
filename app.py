from pathlib import Path

import joblib
import numpy as np
import pandas as pd
import plotly.express as px
import streamlit as st

st.set_page_config(page_title="AtmosPredict AI", page_icon="🌦️", layout="wide")
ROOT = Path(__file__).resolve().parent
DATA_DIR = ROOT / "data"
MODEL_DIR = ROOT / "models"
AQI_FEATURES = ["co aqi value", "ozone aqi value", "no2 aqi value", "pm2.5 aqi value"]
RAIN_FEATURES = ["pressure", "maxtemp", "temparature", "mintemp", "dewpoint", "humidity", "cloud", "sunshine", "winddirection", "windspeed"]

@st.cache_data
def load_data():
    aqi = pd.read_csv(DATA_DIR / "AQI-and-Lat-Long-of-Countries.csv")
    rain = pd.read_csv(DATA_DIR / "Rainfall.csv")
    aqi.columns = [c.strip().lower() for c in aqi.columns]
    rain.columns = [c.strip().lower() for c in rain.columns]
    rain["rainfall"] = rain["rainfall"].astype(str).str.strip().str.lower()
    for c in rain.columns:
        if c != "rainfall":
            rain[c] = pd.to_numeric(rain[c], errors="coerce")
    return aqi, rain

@st.cache_resource
def load_models():
    aqi_path = MODEL_DIR / "aqi_model.joblib"
    rain_path = MODEL_DIR / "rainfall_model.joblib"
    missing = [p.name for p in [aqi_path, rain_path] if not p.exists()]
    if missing:
        raise FileNotFoundError("Missing trained model file(s): " + ", ".join(missing) + ". Run the final deployment-export cell in AtmosPredict_AI_Machine_Learning.ipynb first.")
    aqi_bundle = joblib.load(aqi_path)
    rain_bundle = joblib.load(rain_path)
    return aqi_bundle, rain_bundle

try:
    aqi_df, rain_df = load_data()
    aqi_bundle, rain_bundle = load_models()
    aqi_model = aqi_bundle["model"]
    rain_model = rain_bundle["model"]
except Exception as exc:
    st.error("AtmosPredict AI could not load its data or saved models.")
    st.exception(exc)
    st.stop()

st.title("🌦️ AtmosPredict AI")
st.subheader("Air Quality Index & Rainfall Prediction Using Machine Learning")
st.markdown("The models are trained in the Jupyter Notebook, saved with `joblib`, and loaded here for interactive predictions.")

with st.sidebar:
    st.header("Navigation")
    page = st.radio("Choose a page", ["Overview", "AQI Prediction", "Rainfall Prediction", "Dataset Explorer"])
    st.divider()
    st.caption("Educational estimates only—not official environmental measurements or meteorological forecasts.")
    st.success("Saved notebook models loaded")

if page == "Overview":
    st.header("Project dashboard")
    c1, c2, c3 = st.columns(3)
    c1.metric("AQI dataset rows", f"{len(aqi_df):,}")
    c2.metric("Rainfall dataset rows", f"{len(rain_df):,}")
    c3.metric("Connected saved models", "2")
    st.markdown("### Models loaded from `models/`")
    left, right = st.columns(2)
    with left:
        st.markdown(f"**AQI: {aqi_bundle.get('model_name', 'Saved model')}**")
        for key, value in aqi_bundle.get("metrics", {}).items():
            st.metric(key, f"{value:.4f}")
    with right:
        st.markdown(f"**Rainfall: {rain_bundle.get('model_name', 'Saved model')}**")
        for key, value in rain_bundle.get("metrics", {}).items():
            st.metric(key, f"{value:.4f}")
    st.info("To update the saved models, rerun the final deployment-export cell in the Jupyter Notebook, then restart or refresh this app.")
    st.warning("AQI is estimated from pollutant-specific AQI values, which are related to overall AQI. The rainfall dataset contains only 366 observations, so predictions may not generalize to other places or dates.")

elif page == "AQI Prediction":
    st.header("Air Quality Index prediction")
    st.write("Enter pollutant-specific AQI values. The saved notebook model estimates the overall AQI value.")
    with st.form("aqi_form"):
        a, b = st.columns(2)
        co = a.number_input("CO AQI Value", min_value=0.0, max_value=1000.0, value=1.0, step=1.0)
        ozone = b.number_input("Ozone AQI Value", min_value=0.0, max_value=1000.0, value=30.0, step=1.0)
        no2 = a.number_input("NO₂ AQI Value", min_value=0.0, max_value=1000.0, value=5.0, step=1.0)
        pm25 = b.number_input("PM2.5 AQI Value", min_value=0.0, max_value=1000.0, value=40.0, step=1.0)
        submitted = st.form_submit_button("Predict AQI", type="primary")
    if submitted:
        row = pd.DataFrame([{"co aqi value": co, "ozone aqi value": ozone, "no2 aqi value": no2, "pm2.5 aqi value": pm25}], columns=AQI_FEATURES)
        result = float(aqi_model.predict(row)[0])
        st.success(f"Estimated overall AQI: {result:.1f}")
        st.caption(f"Prediction generated by the saved {aqi_bundle.get('model_name', 'AQI')} model.")

elif page == "Rainfall Prediction":
    st.header("Rainfall prediction")
    st.write("Enter weather observations to estimate whether the saved model classifies the observation as rain or no rain.")
    defaults = {"pressure":1015.0,"maxtemp":28.0,"temparature":25.0,"mintemp":22.0,"dewpoint":20.0,"humidity":75.0,"cloud":60.0,"sunshine":4.0,"winddirection":180.0,"windspeed":12.0}
    labels = {"pressure":"Pressure","maxtemp":"Maximum temperature","temparature":"Temperature","mintemp":"Minimum temperature","dewpoint":"Dew point","humidity":"Humidity (%)","cloud":"Cloud cover","sunshine":"Sunshine (hours)","winddirection":"Wind direction (degrees)","windspeed":"Wind speed"}
    with st.form("rain_form"):
        cols = st.columns(2)
        values = {}
        for i, feature in enumerate(RAIN_FEATURES):
            with cols[i % 2]:
                values[feature] = st.number_input(labels[feature], value=float(defaults[feature]), key=f"rain_{feature}")
        submitted = st.form_submit_button("Predict Rainfall", type="primary")
    if submitted:
        row = pd.DataFrame([values], columns=RAIN_FEATURES)
        pred = int(rain_model.predict(row)[0])
        prob = float(rain_model.predict_proba(row)[0, 1])
        c1, c2 = st.columns(2)
        c1.metric("Prediction", "YES 🌧️" if pred else "NO ☀️")
        c2.metric("Model-estimated rain probability", f"{prob:.1%}")
        st.caption(f"Prediction generated by the saved {rain_bundle.get('model_name', 'rainfall')} model. Probability is not a verified forecast.")

elif page == "Dataset Explorer":
    st.header("Dataset explorer")
    tab1, tab2 = st.tabs(["AQI data", "Rainfall data"])
    with tab1:
        st.write(f"Rows: {aqi_df.shape[0]:,} · Columns: {aqi_df.shape[1]}")
        st.dataframe(aqi_df.head(100), use_container_width=True)
        if "aqi value" in aqi_df.columns:
            fig = px.histogram(aqi_df, x="aqi value", nbins=40, title="Distribution of overall AQI values")
            st.plotly_chart(fig, use_container_width=True)
    with tab2:
        st.write(f"Rows: {rain_df.shape[0]:,} · Columns: {rain_df.shape[1]}")
        st.dataframe(rain_df.head(100), use_container_width=True)
        counts = rain_df["rainfall"].value_counts().rename_axis("Rainfall").reset_index(name="Count")
        fig = px.bar(counts, x="Rainfall", y="Count", title="Rainfall yes/no class balance")
        st.plotly_chart(fig, use_container_width=True)
        numeric = rain_df.select_dtypes(include=np.number).drop(columns=["day"], errors="ignore")
        fig = px.imshow(numeric.corr(), text_auto=".2f", aspect="auto", title="Weather feature correlation heatmap")
        st.plotly_chart(fig, use_container_width=True)

st.divider()
st.caption("AtmosPredict AI · Python · Pandas · scikit-learn · joblib · Plotly · Streamlit")
